def call_button(c, id, label, label_size, icon_size):
    return button(id, c["call"], c["call_drawable"], 16, 12, "ic_phone", icon_size,
                  label=label, label_size=label_size, gap=c["call_gap"])

def home(c, o):
    b = bg("bg_day")
    b += bg("bg_rest", id="bg_rest", visible=False)  # v4 resting/paused, cross-fades with bg_day
    b += glow(c["call"], c["call_radius"])
    b += photo(c["photo_home"], tint=True)
    b += badge(c["badge"])
    b += call_button(c, "call_button", "call_label", c["call_label"], c["call_icon"])
    b += plaque(c)  # over the call button, so the two can blend at wake-up
    b += bird("bird", c["bird_home"])
    b += rest_note(c["bird_home"])
    # failed
    b += text("fail_title", c["fail_title"], c["fail_title_size"], visible=False)
    b += text("fail_subtitle", c["fail_subtitle"], c["subtitle_size"], font="fredoka_medium",
              color="gp_text_secondary", visible=False)
    # v4 missed call (the designer's preview shows both lines in navy)
    b += text("missed_title", c["missed_title"], c["missed_title_size"], visible=False)
    b += text("missed_subtitle", c["missed_subtitle"], c["subtitle_size"], font="fredoka_medium", visible=False)
    # v4 resting / paused (textColor gp_navy for both lines)
    b += text("rest_title", c["rest_title"], c["title_size"], visible=False)
    b += text("rest_subtitle", c["rest_subtitle"], c["subtitle_size"], font="fredoka_medium", visible=False)
    # offline
    b += text("off_title", c["off_title"], c["title_size"], visible=False, autosize=False)
    b += text("off_subtitle", c["off_subtitle"], c["subtitle_size"], font="fredoka_medium",
              color="gp_text_secondary", visible=False)
    b += button("retry_button", c["retry"], "btn_retry_bg", 8, 4, "ic_retry", 46, icon_tint="gp_navy",
                label="retry", label_size=40, label_color="gp_navy", gap=16)
    b += bird("bird_offline", c["bird_offline"])
    b += lock_hold()
    return screen(b)

def incoming(c, o):
    b = bg("bg_incoming")
    b += glow(c["call"], c["call_radius"])
    b += photo(c["photo_incoming"])
    # Decline comes after the photo so it is drawn (and touched) on top of it.
    x, y, w, h = c["decline"]
    r = 16  # ring margin around decline: not in the designer's file, mirrors hang-up (168 vs 136)
    b += ring("decline_ring", (x - r, y - r, w + 2 * r, h + 2 * r), stroke=10, color="gp_red")
    b += button("decline_button", c["decline"], "btn_decline_bg", 0, 0, "ic_hangup", int(w * 0.47),
                icon_tint="gp_red", desc="cd_decline")
    b += chip("decline_hint", c["hint_size"], "decline_hint", top=c["decline_hint"][1], left=c["decline_hint"][0])
    b += call_button(c, "answer_button", "answer_label", c["answer_label"], c["answer_icon"])
    b += notes(c["notes"])
    b += bird("bird", c["bird_home"])
    b += text("countdown", c["countdown"], c["countdown_size"], font="fredoka_medium", color="gp_navy")
    return screen(b)

def call(c, o):
    b = bg("bg_day")
    b += ripples(c["photo_home"])
    # v4 in call without video: rings under the photo, badge and hint over it.
    b += voice_rings(c["photo_novideo"])
    b += photo(c["photo_home"])
    b += camera_badge(c["camera_badge"])
    b += center_chip("video_hint", c["video_hint"][1], "waiting_video", top=c["video_hint"][0])
    b += bird("bird", c["bird_calling"])
    b += text("calling_label", c["calling_label"], c["calling_size"], lines=2)
    # Remote video: sized/positioned in code to cover the screen with a top-biased crop. Above the
    # photo and its rings, hint and badge (v4 "videoArrives": it fades in over them), under the
    # self-view and the hang-up button.
    b += ('    <FrameLayout android:id="@+id/video_container" android:layout_width="match_parent"\n'
          '        android:layout_height="match_parent" android:background="@color/black"\n'
          '        android:visibility="gone">\n'
          '        <TextureView android:id="@+id/remote_video" android:layout_width="match_parent"\n'
          '            android:layout_height="match_parent" />\n'
          '    </FrameLayout>\n')
    b += (f'    <com.abufon.app.RoundedClipLayout android:id="@+id/self_frame"\n        {pos(c["self"])}\n'
          '        android:visibility="gone" android:contentDescription="@string/cd_self_view">\n'
          '        <com.abufon.app.SelfView android:id="@+id/self_view"\n'
          '            android:layout_width="match_parent" android:layout_height="match_parent" />\n'
          '        <View android:layout_width="match_parent" android:layout_height="match_parent"\n'
          '            android:background="@drawable/bg_selfview_frame" />\n'
          '    </com.abufon.app.RoundedClipLayout>\n')
    b += ring("hangup_ring", c["hang_ring"])
    b += button("hangup_button", c["hangup"], "btn_hangup_bg", 8, 4, "ic_hangup", 68, desc="cd_hangup")
    b += chip("hangup_hint", c["hint_size"], "hangup_hint", top=c["hang_hint"][1],
              right_edge=c["hang_hint"][0], canvas_w=CANVAS[o][0])
    return screen(b)

